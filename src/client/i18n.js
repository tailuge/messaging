const isKorean = typeof navigator !== 'undefined' && navigator.language.startsWith("ko");

/**
 * Translates an English phrase to Korean if the browser language is set to Korean.
 * Falls back to the English phrase if no translation is found or if not in Korean mode.
 * Supports simple parameter replacement using {key} syntax.
 *
 * @param {string} english - The English phrase to translate.
 * @param {Object} [params={}] - Optional parameters for replacement.
 * @returns {string} The translated string.
 */
export function t(english, params = {}) {
    let text = isKorean ? (ko[english] ?? english) : english;

    for (const [key, value] of Object.entries(params)) {
        text = text.replace(`{${key}}`, value);
    }

    return text;
}
